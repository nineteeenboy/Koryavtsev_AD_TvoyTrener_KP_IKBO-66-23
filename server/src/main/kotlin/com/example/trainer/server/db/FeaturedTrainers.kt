/** Adds supplied profiles once and refreshes their text without replacing IDs, bookings or tariffs. */
fun seedFeaturedTrainers(database: DatabaseFactory) = transaction(database.database) {
    val year = LocalDate.now(ZoneId.of("Europe/Moscow")).year
    profiles.forEachIndexed { index, profile ->
        val photo = "/media/trainers/trainer_${index + 1}.jpg"
        val existing = Trainers.selectAll().where { Trainers.photoUrl eq photo }.singleOrNull()
        if (existing == null) {
            Trainers.insert {
                it[name] = profile.role
                it[specialization] = profile.specialty
                it[photoUrl] = photo
                it[description] = profile.description
                it[experienceYears] = profile.since?.let { since -> year - since } ?: 0
                it[price] = profile.price.toBigDecimal()
            }
        } else {
            Trainers.update({ Trainers.id eq existing[Trainers.id] }) {
                it[name] = profile.role
                it[specialization] = profile.specialty
                it[description] = profile.description
                it[experienceYears] = profile.since?.let { since -> year - since } ?: 0
            }
        }
    }
}

